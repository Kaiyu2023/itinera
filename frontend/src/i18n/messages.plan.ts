type PlanTranslate = (key: keyof typeof planEnglish, values?: Record<string, string | number>) => string;

/** Compound durations are generated UI text, not itinerary content. */
export function formatPlanDuration(minutes: number, t: PlanTranslate): string {
  const hours = Math.floor(minutes / 60);
  const remainder = minutes % 60;
  if (hours === 0) return t('plan.duration.minutes', { minutes: remainder });
  return remainder === 0
    ? t('plan.duration.hours', { hours })
    : t('plan.duration.hoursMinutes', { hours, minutes: remainder });
}

export function formatPlanDistance(metres: number, locale: 'en' | 'zh-CN', t: PlanTranslate): string {
  const distance = new Intl.NumberFormat(locale, { minimumFractionDigits: 1, maximumFractionDigits: 1 }).format(
    metres / 1000,
  );
  return t('plan.distance.kilometres', { distance });
}
